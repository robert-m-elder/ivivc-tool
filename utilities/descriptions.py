CV_SCHEME_LABELS = {
    'shuffle_split': 'Shuffle split',
    'kfold': 'K-fold',
    'leave_one_out': 'Leave-one-out',
    'none': 'None',
}

ANALYSIS_CONFIG_LABELS = {
    'cv_scheme': 'Cross-validation scheme',
    'cv_n_splits': 'CV splits/folds',
    'cv_test_size': 'ShuffleSplit test size',
    'cv_random_state': 'CV random seed',
    'grid_search_num_points': 'Grid-search random starts',
    'grid_search_num_cores': 'Grid-search CPU cores',
    'grid_search_param_min': 'Grid-search parameter minimum',
    'grid_search_param_max': 'Grid-search parameter maximum',
}


def format_analysis_config_rows(config):
    """Return display-ready (label, value) rows for results and reports."""
    scheme = config.get('cv_scheme', 'shuffle_split')
    rows = []

    for key in [
        'cv_scheme',
        'cv_n_splits',
        'cv_test_size',
        'cv_random_state',
        'grid_search_num_points',
        'grid_search_num_cores',
        'grid_search_param_min',
        'grid_search_param_max',
    ]:
        value = config.get(key, '')
        if key == 'cv_scheme':
            value = CV_SCHEME_LABELS.get(value, value)
        elif key == 'cv_test_size' and scheme != 'shuffle_split':
            value = 'N/A'
        elif key == 'grid_search_num_cores' and value in (None, ''):
            value = 'Auto'
        rows.append((ANALYSIS_CONFIG_LABELS[key], value))

    return rows
